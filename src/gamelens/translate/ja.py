def normalize(text: str) -> str:
    """全角英文数字转半角、去多余空白。"""
    out = []
    for ch in text:
        code = ord(ch)
        if 0xFF01 <= code <= 0xFF5E:        # 全角 ASCII
            out.append(chr(code - 0xFEE0))
        elif code == 0x3000:                 # 全角空格
            out.append(" ")
        else:
            out.append(ch)
    text = "".join(out)
    text = re.sub(r"\s+", " ", text).strip()
    return text


class JaMT(TranslateEngine):
    """日文 → 中文离线引擎。"""

    name = "litemt"
    label = "LiteMT 内置离线引擎（日→中）"
    offline = True
    supports_batch = True
    max_batch = 128

    def __init__(self) -> None:
        self._keys = sorted(JA_PHRASES, key=len, reverse=True)
        self._maxlen = max(len(k) for k in self._keys) if self._keys else 1

    def translate(self, texts: Sequence[str], src: str = "ja", dst: str = "zh") -> List[str]:
        return [self.one(t) for t in texts]

    # ------------------------------------------------------------------
    def one(self, text: str) -> str:
        raw = normalize(text)
        if not raw:
            return ""
        # 纯英文/数字（标题 LOGO、厂商名）别硬翻，原样放过，免得被拆成 "TOUCHTOSTART"
        if not _KANA.search(raw) and not _KANJI.search(raw):
            return raw
        body = _PUNCT_TAIL.sub("", raw)
        tail = raw[len(body):]

        # 1) 整句命中
        hit = JA_PHRASES.get(body)
        if hit:
            return self._finish(hit, tail)

        # 2) 句型规则（递归处理槽位）
        for rx, tpl in PATTERN_RES:
            m = rx.match(body)
            if not m:
                continue
            slots = {}
            ok = True
            for i, g in enumerate(m.groups(), start=1):
                sub = self.one(g) if g else ""
                if not sub or not self._is_zh(sub):
                    ok = False
                    break
                slots[str(i)] = sub
            if not ok:
                continue
            out = tpl
            for k, v in slots.items():
                out = out.replace("{" + k + "}", v)
            return self._finish(out, tail)

        # 3) 最长匹配 + 助词 + 语序
        out = self._segment(raw)
        return self._finish(out, tail) if out else ""

    # ------------------------------------------------------------------
    @staticmethod
    def _is_zh(text: str) -> bool:
        return bool(_KANJI.search(text))

    def _segment(self, text: str) -> str:
        """切成实词/助词，再按"动词提前"重排成中文语序。"""
        parts: List[Tuple[str, str, bool]] = []   # (原文, 译文, 是否助词)
        i, n = 0, len(text)
        while i < n:
            ch = text[i]
            if ch.isspace() or ch in "、。！？!?…":
                i += 1
                continue
            matched = False
            for size in range(min(self._maxlen, n - i), 0, -1):
                piece = text[i:i + size]
                zh = JA_PHRASES.get(piece)
                if zh is not None:
                    parts.append((piece, zh, piece in PARTICLES))
                    i += size
                    matched = True
                    break
            if matched:
                continue
            # 单个助词
            for p, zh in PARTICLES.items():
                if text.startswith(p, i):
                    parts.append((p, zh, True))
                    i += len(p)
                    matched = True
                    break
            if matched:
                continue
            # 片假名连写：整体保留（多半是外来语专名）
            if _KANA.match(ch):
                j = i
                while j < n and _KANA.match(text[j]):
                    j += 1
                parts.append((text[i:j], text[i:j], False))
                i = j
                continue
            # 其余（未收录的汉字词/英文/数字）原样保留
            parts.append((ch, ch, False))
            i += 1

        if not parts:
            return ""

        # 句末是动词 → 把它提到宾语前面：ご飯を食べる → 吃米饭
        verb_idx = None
        for idx in range(len(parts) - 1, -1, -1):
            if not parts[idx][2]:
                if parts[idx][1] in VERBS_ZH:
                    verb_idx = idx
                break
        if verb_idx is not None and verb_idx > 0:
            obj = [p for p in parts[:verb_idx] if not p[2]]
            rest = [p for p in parts[verb_idx + 1:] if not p[2]]
            if obj:
                head = [p for p in parts[:verb_idx] if p[2] and p[1]]
                verb = parts[verb_idx][1]
                text_obj = "".join(p[1] for p in obj[-1:])
                prefix = "".join(p[1] for p in head)
                return f"{prefix}{verb}{text_obj}" + "".join(p[1] for p in rest)

        out = "".join(p[1] for p in parts)
        # 助词残留的中文关系词做点润色
        out = re.sub(r"(在|往|和|的){2,}", r"\1", out)
        out = re.sub(r"的+", "的", out)
        return out

    @staticmethod
    def _finish(out: str, tail: str) -> str:
        out = out.strip()
        if not out:
            return ""
        if "？" in tail or "?" in tail:
            if not out.endswith(("？", "?")):
                out += "？"
        elif "！" in tail or "!" in tail:
            if not out.endswith(("！", "!")):
                out += "！"
        elif out and _KANJI.search(out) and not out.endswith(("。", "！", "？", "…")):
            if tail:
                out += "。"
        return out
